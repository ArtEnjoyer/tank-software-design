package ru.mipt.bit.platformer.model.state;

/**
 * Доменный интерфейс (domain) шаблона «Состояние».
 * Задаёт множители времени движения и перезарядки, а также разрешение стрельбы.
 * Не является портом внешней системы. Новое поведение вводится отдельной реализацией.
 * Состояние определяет параметры оружия, но не хранит его таймер перезарядки.
 */
public interface TankState {

    float movementDurationMultiplier();

    /**
     * Множитель базового времени перезарядки оружия: 1 — обычная скорость,
     * 0.5 — перезарядка вдвое быстрее. Значение должно быть положительным и конечным.
     *
     * @return множитель длительности перезарядки
     */
    default float reloadDurationMultiplier() {
        return 1f;
    }

    boolean canShoot();
}
