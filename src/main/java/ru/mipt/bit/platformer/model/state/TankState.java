package ru.mipt.bit.platformer.model.state;

/**
 * Доменный интерфейс (domain) шаблона «Состояние».
 * Задаёт множитель времени движения и разрешение стрельбы; не является портом
 * внешней системы. Новое поведение вводится отдельной реализацией.
 * Для будущего ускорения стрельбы контракт потребуется расширить параметром
 * перезарядки: сейчас частота выстрелов задаётся непосредственно в {@code Gun}.
 */
public interface TankState {

    float movementDurationMultiplier();

    boolean canShoot();
}
